CREATE TABLE public.parametros_entrevista_opciones (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  familia VARCHAR(60) NOT NULL,
  codigo VARCHAR(80) NOT NULL,
  etiqueta VARCHAR(120) NOT NULL,
  etiqueta_normalizada VARCHAR(120) NOT NULL,
  orden INTEGER NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_by UUID NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  updated_by UUID NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT chk_parametros_entrevista_familia CHECK (familia IN (
    'COMO_CONOCIO_ASESORA', 'ANTIGUEDAD_CONOCE_GRUPO', 'MOTIVO_DESACUERDO_MONTOS',
    'MOTIVO_NO_RENOVACION', 'MOTIVO_NO_VIVE_DOMICILIO', 'TIPO_DOMICILIO',
    'FAMILIAR_DOMICILIO', 'ANTIGUEDAD_DOMICILIO', 'PERSONAS_VIVEN_CASA',
    'CONVIVIENTES', 'FUENTES_INGRESO', 'ANTIGUEDAD_LABORAL',
    'MOTIVO_SIN_CONTROL_PAGOS', 'FRECUENCIA_SERVICIO', 'CALIFICACION_SERVICIO',
    'RAPIDEZ_DESEMBOLSO', 'MOTIVO_RECOMENDACION_SI', 'MOTIVO_RECOMENDACION_NO'
  )),
  CONSTRAINT chk_parametros_entrevista_orden CHECK (orden >= 1),
  CONSTRAINT chk_parametros_entrevista_codigo CHECK (btrim(codigo) <> ''),
  CONSTRAINT chk_parametros_entrevista_etiqueta CHECK (char_length(btrim(etiqueta)) >= 1),
  CONSTRAINT uq_parametros_entrevista_codigo UNIQUE (familia, codigo),
  CONSTRAINT uq_parametros_entrevista_etiqueta UNIQUE (familia, etiqueta_normalizada),
  CONSTRAINT uq_parametros_entrevista_orden UNIQUE (familia, orden) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX idx_parametros_entrevista_activos
  ON public.parametros_entrevista_opciones (familia, orden) WHERE activo = TRUE;

