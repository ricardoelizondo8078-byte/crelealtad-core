-- RESUMEN FINAL
SELECT
    'TOTAL CÓDIGOS POSTALES' as descripcion,
    COUNT(*) as cantidad
FROM codigos_postales
UNION ALL
SELECT
    'TOTAL MUNICIPIOS' as descripcion,
    COUNT(DISTINCT municipio) as cantidad
FROM codigos_postales
UNION ALL
SELECT
    'TOTAL COLONIAS' as descripcion,
    COUNT(DISTINCT colonia) as cantidad
FROM codigos_postales;
